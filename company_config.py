def format_money(value):
    """Форматирование суммы. value — в тенге (если values_in_kzt) или USD."""
    if CURRENCY.get("values_in_kzt", False):
        if CURRENCY["display"] == "KZT":
            return f"{value:,.0f} {CURRENCY['symbol']}"
        return f"${value / CURRENCY['usd_to_kzt']:,.0f}"
    if CURRENCY["display"] == "KZT":
        return f"{value * CURRENCY['usd_to_kzt']:,.0f} {CURRENCY['symbol']}"
    return f"${value:,.0f}"

def to_display_currency(value):
    if CURRENCY.get("values_in_kzt", False):
        return value if CURRENCY["display"] == "KZT" else value / CURRENCY["usd_to_kzt"]
    return value * CURRENCY["usd_to_kzt"] if CURRENCY["display"] == "KZT" else value

